//! A repository's rules file, rendered: the rules `ris` gives every
//! project, then the project's own part, which the repository keeps in
//! a file of its own. The person renders it (`ris rules --render`), so
//! a change to the rules template reaches the file the seats read
//! without anyone patching that file by hand, and a seat still never
//! writes its own rules.
//!
//! A rendered file's first line names its source and itself, so the
//! file is found and rendered again with nothing configured: the
//! closing merge of a phase does that ([`rerender`]), and `ris rules
//! --render ... --check` says whether a file is current ([`stale`])
//! without writing it.

use std::path::{Component, Path};

use crate::project::{CliError, RULES};

/// How a rendered file opens, up to the source it names.
const HEADER: &str = "<!-- Rendered by `ris rules --render ";

/// The rendered file: a comment naming the command that renders it and
/// its sources, the rules template, and `project` as it is written.
/// `source` and `to` are the paths the command was given, which the
/// comment repeats, so the file says how to render it again.
pub fn render(source: &str, to: &str, project: &str) -> String {
    format!(
        "{HEADER}{source} --to {to}`: the rules ris gives every \
         project, then this project's own, from {source}. Do not edit this file: change the \
         source, or the rules in ris, and render it again. -->\n\n{}\n\n{}\n",
        RULES.trim_end(),
        project.trim()
    )
}

/// A path as the rendered file may name it: relative, with no `..` and
/// no backslash, so the file never carries where a checkout lives.
pub fn named(path: &Path) -> Result<String, CliError> {
    let plain = path
        .components()
        .all(|c| matches!(c, Component::Normal(_) | Component::CurDir));
    match path.to_str() {
        Some(s) if plain && !s.contains('\\') => Ok(s.trim_start_matches("./").to_owned()),
        _ => Err(CliError::Other(format!(
            "refused: `{}` is not a path inside the directory this runs in\n  \
             next: run it at the repository root with relative paths, as in \
             `ris rules --render docs/project-rules.md --to AGENTS.md`",
            path.display()
        ))),
    }
}

/// Render the project part at `source` into the rules file at `to`,
/// both relative to `dir`. `true` when the file changed.
pub fn write(dir: &Path, source: &Path, to: &Path) -> Result<bool, CliError> {
    let (source_name, to_name) = (named(source)?, named(to)?);
    let project = std::fs::read_to_string(dir.join(source)).map_err(|e| {
        CliError::Other(format!(
            "could not read the project's part of the rules at {source_name}: {e}\n  \
             next: write what is specific to this project there, and run this again"
        ))
    })?;
    let rendered = render(&source_name, &to_name, &project);
    let path = dir.join(to);
    if std::fs::read_to_string(&path).is_ok_and(|now| now == rendered) {
        return Ok(false);
    }
    std::fs::write(&path, rendered)?;
    Ok(true)
}

/// The source and the rules file that `text`, a rendered file, names
/// in its first line. `None` for a file that was not rendered.
pub fn sources(text: &str) -> Option<(String, String)> {
    let command = text.lines().next()?.strip_prefix(HEADER)?;
    let (command, _) = command.split_once('`')?;
    let (source, to) = command.split_once(" --to ")?;
    Some((source.to_owned(), to.to_owned()))
}

/// Why the rules file at `to` is not what the project part at `source`
/// renders, both relative to `dir`: the first line where they differ.
/// `None` when the file is current. Nothing is written.
pub fn stale(dir: &Path, source: &Path, to: &Path) -> Result<Option<String>, CliError> {
    let (source_name, to_name) = (named(source)?, named(to)?);
    let read = |path: &Path, name: &str| {
        std::fs::read_to_string(dir.join(path))
            .map_err(|e| CliError::Other(format!("could not read {name}: {e}")))
    };
    let project = read(source, &source_name)?;
    let committed = read(to, &to_name)?;
    let rendered = render(&source_name, &to_name, &project);
    if committed == rendered {
        return Ok(None);
    }
    let line = committed
        .lines()
        .zip(rendered.lines())
        .position(|(a, b)| a != b)
        .unwrap_or_else(|| committed.lines().count().min(rendered.lines().count()));
    let at = |text: &str| format!("{:?}", text.lines().nth(line).unwrap_or("(the file ends)"));
    Ok(Some(format!(
        "{to_name} is not what the rules and {source_name} render; they first differ at line {}:\n  \
         in the file: {}\n  rendered:    {}",
        line + 1,
        at(&committed),
        at(&rendered),
    )))
}

/// Render again every rendered rules file at the root of `dir`: each
/// file an agent tool loads from there whose first line names it and
/// its source. Returns the rules file and the source of each one that
/// changed. A file that names another file, or a source outside `dir`,
/// is left as it is.
pub fn rerender(dir: &Path) -> Result<Vec<(String, String)>, CliError> {
    let mut changed = Vec::new();
    for name in crate::runner::RULES_FILES {
        let Some((source, to)) = std::fs::read_to_string(dir.join(name))
            .ok()
            .and_then(|text| sources(&text))
        else {
            continue;
        };
        if to != *name || named(Path::new(&source)).is_err() {
            continue;
        }
        if write(dir, Path::new(&source), Path::new(&to))? {
            changed.push((to, source));
        }
    }
    Ok(changed)
}

